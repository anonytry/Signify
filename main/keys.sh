#!/bin/bash
# AOSP Key Generation Backend

# Set working directory to KEYS_DIR
TARGET_DIR="${ROM_ROOT}/${KEYS_DIR}"
mkdir -p "${TARGET_DIR}"

# --- Makefile Parsing & Generation ---
# Extract override certificates - strictly alphanumeric to avoid noise
OVERRIDE_CERTS=$(grep "PRODUCT_CERTIFICATE_OVERRIDES" keys.mk | grep -oP '(?<=:)[a-zA-Z0-9\._-]+' | grep -v "=" | sort -u)

# Generate Android.bp in target dir
echo "// DO NOT EDIT THIS FILE MANUALLY" > "${TARGET_DIR}/Android.bp"

for cert in $OVERRIDE_CERTS; do
    {
        echo ""
        echo "android_app_certificate {"
        echo "    name: \"$cert\","
        echo "    certificate: \"$cert\","
        echo "}"
    } >> "${TARGET_DIR}/Android.bp"
done

# Check if gmscompat_lib is mentioned
GMS_COMPAT=$(grep -c "gmscompat_lib" keys.mk)
if [[ $GMS_COMPAT -gt 0 ]]; then
    {
        echo ""
        echo "android_app_certificate {"
        echo "    name: \"gmscompat_lib.certificate.override\","
        echo "    certificate: \"gmscompat_lib.certificate.override\","
        echo "}"
    } >> "${TARGET_DIR}/Android.bp"
fi

# --- Patch/Generate keys.mk in target dir ---
# Start with a clean copy of the original
cp keys.mk "${TARGET_DIR}/keys.mk"

# Append our dynamic overrides at the end to ensure they take precedence
{
    echo ""
    echo "# --- Signify Dynamic Configuration ---"
    echo "PRODUCT_DEFAULT_DEV_CERTIFICATE := ${KEYS_DIR}/releasekey"
    echo "PRODUCT_MAINLINE_BLUETOOTH_SEPOLICY_DEV_CERTIFICATES := \$(dir \$(PRODUCT_DEFAULT_DEV_CERTIFICATE))"
    echo "PRODUCT_OTA_PUBLIC_KEYS := ${KEYS_DIR}/otakey.x509.pem"
    
    if [[ $GMS_COMPAT -gt 0 ]]; then
        echo "PRODUCT_CERTIFICATE_GMSCOMPAT_LIB := ${KEYS_DIR}/gmscompat_lib"
    fi
} >> "${TARGET_DIR}/keys.mk"

# --- Key Generation Phase ---
echo -e "\n${BLUE}--> Processing keys in: ${NC}${TARGET_DIR}"

gen_key() {
    local name=$1
    local path="${TARGET_DIR}/${name}"
    
    if [[ -f "${path}.pk8" ]]; then
        echo -e "    ${YELLOW}[EXISTS]${NC} $name"
    else
        echo -e "    ${GREEN}[GEN]${NC} $name"
        ./make_key.sh "$path" "${KEY_SIZE:-4096}" > /dev/null 2>&1
    fi
}

# 1. Standard AOSP keys
# Always generate core keys
gen_key "releasekey"
gen_key "platform"
gen_key "shared"
gen_key "media"
gen_key "networkstack"
gen_key "sdk_sandbox"
gen_key "bluetooth"
gen_key "nfc"

# Explicit OTA Generation
if [[ "$SKIP_OTA" == "true" || "$SKIP_OTA" == "yes" ]]; then
    echo -e "    ${YELLOW}[SKIPPED]${NC} otakey"
else
    gen_key "otakey"
fi

# 2. Override keys from keys.mk
for cert in $OVERRIDE_CERTS; do
    gen_key "$cert"
done

# 3. GMS Compat Overrides
if [[ $GMS_COMPAT -gt 0 ]]; then
     gen_key "gmscompat_lib.certificate.override"
     gen_key "gmscompat_lib"
fi
